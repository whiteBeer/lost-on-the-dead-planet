const assert = require('node:assert/strict');
const { mkdtempSync, statSync } = require('node:fs');
const { tmpdir } = require('node:os');
const { join } = require('node:path');
const { randomBytes } = require('node:crypto');
const { ProfileStore } = require('../dist/classes/ProfileStore');
const { Scene } = require('../dist/components/Scene');
const { coinsForLevel } = require('../dist/configs/Shop');
const { expForLevel } = require('../dist/configs/Waves');

const directory = mkdtempSync(join(tmpdir(), 'wave-economy-'));
const file = join(directory, 'profiles.json');
const store = new ProfileStore(file);
const key = store.ensureToken(randomBytes(32).toString('hex'));
assert.throws(() => store.ensureToken('bad'));
assert.deepEqual([1, 2, 5, 6, 10, 11].map(coinsForLevel), [0, 1, 1, 2, 2, 3]);
const scene = new Scene('economy-test', store);
try {
    const a = scene.playersCollection.addPlayer('a');
    const b = scene.playersCollection.addPlayer('b');
    a.bindProfile(key);
    for (let level = 2; level <= 12; level++) {
        a.exp = expForLevel(a.level);
        a.checkLevelUp();
        const expected = level <= 5 ? level - 1 : level <= 10 ? 4 + (level - 5) * 2 : 14 + (level - 10) * 3;
        assert.equal(store.view(key).coins, expected, `level ${level}`);
    }
    assert.equal(a.runCoins, 20);
    assert.equal(a.toJSON().coins, 20);
    assert.equal(store.rewardLevel(key, scene.runId, 12), 0, 'same level cannot be awarded twice');
    assert.equal(new ProfileStore(file).view(key).coins, 20, 'coins survive reload');
    assert.equal(statSync(file).mode & 0o777, 0o600);
    assert.throws(() => store.buy(key, 'unknown'));
    assert.throws(() => store.buy(key, 'spectre'));
    assert.throws(() => store.equip(key, 'ember'));
    assert.equal(store.buy(key, 'ember').coins, 5);
    assert.equal(store.buy(key, 'ember').coins, 5, 'double-click cannot charge twice');
    assert.equal(store.equip(key, 'ember').selected, 'ember');
    assert.equal(new ProfileStore(file).view(key).selected, 'ember', 'purchase and selection survive restart');
    b.addWeapon('SMG');
    b.equipInventorySlot(1);
    b.level = 7;
    b.exp = 12;
    b.isDead = true;
    b.health = 0;
    const gear = b.weapon;
    const perkCount = b.perks.length;
    scene.phase = 'playing';
    const director = scene.waveDirector;
    director.wave = 1;
    director.started = true;
    director.active = true;
    let revived = 0;
    scene.on('playersRevived', event => { revived += event.players.length; });
    director.onEnemiesCleared();
    assert.equal(b.isDead, false);
    assert.equal(b.health, b.maxHealth);
    assert.equal(b.weapon, gear);
    assert.equal(b.weapon.ammo, b.weapon.getClipSize());
    assert.equal(b.level, 7);
    assert.equal(b.exp, 12);
    assert.equal(b.perks.length, perkCount);
    assert.equal(revived, 1);
    director.onEnemiesCleared();
    assert.equal(revived, 1, 'clear event cannot revive twice');
    assert.equal(store.view(key).coins, 5, 'revival does not award levels again');
    director.reset();
    a.isDead = true;
    b.isDead = true;
    director.active = true;
    director.wave = 2;
    director.onEnemiesCleared();
    assert(a.isDead && b.isDead, 'no resurrection if everyone died');
    scene.wipeIfNoSurvivors();
    scene.newGame();
    assert.equal(a.skinId, 'ember', 'selected skin also applies when restarting the same room');
    assert.equal(a.level, 1);
    assert.equal(a.runCoins, 0);
    a.exp = expForLevel(1);
    a.checkLevelUp();
    assert.equal(store.view(key).coins, 6, 'new run awards fresh levels, while wallet remains');
    director.reset();
    scene.phase = 'playing';
    b.isDead = true;
    b.health = 0;
    director.active = true;
    director.wave = 10;
    director.onEnemiesCleared();
    assert.equal(b.isDead, false);
    assert.equal(scene.getPhase(), 'won', 'final-wave revival precedes victory');
    console.log(JSON.stringify({ ok: true, levelThresholds: true, replayProtection: true, purchases: true, persistence: true, coopRevive: true, noSurvivorWipe: true, finalWaveRevive: true }));
} finally {
    scene.destroy();
}
